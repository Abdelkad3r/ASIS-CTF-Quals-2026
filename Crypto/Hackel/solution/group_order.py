"""
Hackel - supporting analysis.

Deterministic Schreier-Sims computation of the order of the group generated by a
submitted key, used to show that the verifier's `is_symmetric_gen` gate constrains
almost nothing: our submission generates all of S_11, while AGL(1,11) of order 110
passes exactly the same checks.

Usage:  python3 group_order.py
"""

N = 11
def comp(a, b): return tuple(b[i] for i in a)          # a then b
def inv(p):
    o = [0]*len(p)
    for i, v in enumerate(p): o[v] = i
    return tuple(o)
ID = tuple(range(N))

def cyc(pts):
    o = list(range(N))
    for i, p in enumerate(pts): o[p] = pts[(i+1) % len(pts)]
    return tuple(o)

def orbit_transversal(base, gens):
    """Return {pt: g} with base^g = pt, using our left-to-right convention (pt = g[base])."""
    T = {base: ID}
    frontier = [base]
    while frontier:
        nxt = []
        for pt in frontier:
            for g in gens:
                img = g[pt]
                if img not in T:
                    T[img] = comp(T[pt], g)
                    nxt.append(img)
        frontier = nxt
    return T

def group_order(gens):
    gens = [g for g in gens if g != ID]
    if not gens:
        return 1
    # pick a base point actually moved
    base = next(i for i in range(N) if any(g[i] != i for g in gens))
    T = orbit_transversal(base, gens)
    # Schreier generators for the stabilizer of `base`
    schreier = set()
    for pt, u in T.items():
        for g in gens:
            s = comp(comp(u, g), inv(T[g[pt]]))
            if s != ID:
                schreier.add(s)
    return len(T) * group_order(sorted(schreier))

A = cyc(tuple(range(10)))     # 10-cycle fixing point 10
B = cyc(tuple(range(11)))     # 11-cycle
C = comp(A, B); D = comp(inv(A), comp(B, C)); E = comp(C, D)

import math
o = group_order([A, B])
print(f"|<A,B>|            = {o:,}")
print(f"11!                = {math.factorial(11):,}")
print(f"11!/2              = {math.factorial(11)//2:,}")
print(f"is S_11            = {o == math.factorial(11)}")
print(f"|<A,B,C,D,E>|      = {group_order([A,B,C,D,E]):,}")

# sanity: the Frobenius group F110 = AGL(1,11) for comparison
t = tuple((i+1) % 11 for i in range(11))              # x -> x+1
m = tuple((i*2) % 11 for i in range(11))              # x -> 2x  (2 is a primitive root mod 11)
print(f"|AGL(1,11)|        = {group_order([t, m]):,}  (the 'expected' 11:10 answer)")
